export const dictionaries: Record<UiLocale, Record<TranslationKey, string>> = { en, bn };

export const LOCALE_LABEL: Record<UiLocale, string> = {
  en: "English",
  bn: "বাংলা",
};

/** Replaces {name} placeholders. Missing keys fall back to English, then the key. */
export function translate(
  locale: UiLocale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const raw = dictionaries[locale]?.[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] === undefined ? match : String(vars[name])
  );
}
